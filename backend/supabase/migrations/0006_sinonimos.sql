-- Igual que en 0002, pero cada palabra cuenta como encontrada si aparece ella o cualquiera de sus sinónimos.
create or replace function search_products(q text, match_all boolean default true, max_results int default 50)
returns setof products
language sql stable
set search_path = public as $$
  with words as (
    -- Sin plural ni género en palabras largas: "negras"/"negro" -> "negr".
    select distinct w0 as raw, case when length(w0) > 4 then regexp_replace(w0, '(e?s|[ao]s?)$', '') else w0 end as w,
           regexp_replace(w0, 'e?s$', '') as sg
    from unnest(regexp_split_to_array(normalize_es(q), '[^a-z0-9./-]+')) as w0
    where (length(w0) >= 3 or w0 ~ '\d')
      and w0 <> all (array['una', 'uno', 'unos', 'unas', 'los', 'las', 'del', 'con', 'sin', 'para', 'por',
                           'que', 'como', 'cual', 'cuales', 'hay', 'tiene', 'tienen', 'tienes', 'necesito',
                           'quiero', 'busco', 'venden', 'vende', 'precio', 'cuanto', 'cuesta', 'hola',
                           'gracias', 'favor', 'algun', 'alguna', 'esta', 'este', 'eso', 'esto', 'mas'])
  ),
  alts as (
    select w.raw, w.w as alt from words w
    union
    select w.raw, s2.term from words w
    join search_synonyms s1 on s1.term in (w.raw, w.w, w.sg)
    join search_synonyms s2 on s2.group_id = s1.group_id
  ),
  scored as (
    select p,
           (select count(distinct a.raw) from alts a where p.search_text like '%' || a.alt || '%') as hits,
           (select count(*) from words) as total
    from products p
    where not p.discontinued
  )
  select (s.p).*
  from scored s
  where s.total > 0 and (case when match_all then s.hits = s.total else s.hits > 0 end)
     or (s.p).reference ilike trim(q)
  order by ((s.p).reference ilike trim(q)) desc, s.hits desc, (s.p).reference
  limit greatest(1, least(max_results, 200));
$$;

grant execute on function search_products(text, boolean, int) to anon, authenticated;
